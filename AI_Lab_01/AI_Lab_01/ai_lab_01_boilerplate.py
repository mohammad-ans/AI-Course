def read_file(filename):
    """
    Reads the grid from a text file.
    Returns number of rows, columns, and the grid as a list of lists.
    """
    with open(filename, "r") as file:
        rows, cols = map(int, file.readline().split())
        grid = []
        for _ in range(rows):
            grid.append(file.readline().split())
    return rows, cols, grid

# -----------------------------
# Task 1: State Space Functions
# -----------------------------
def get_state(row, col):
    """
    Returns the current state as coordinates (row, col).
    """
    return (row, col)

def initial_state(grid):
    """
    Finds and returns the initial state 'S' in the grid.
    """
    for i, row in enumerate(grid):
        for j, point in enumerate(row):
            if point == 'S':
                return (i, j)

def goal_test(state, grid):
    """
    Returns True if the current state is the goal 'G'.
    """
    return grid[state[0]][state[1]] == 'G'

def actions(state, grid, rows, cols):
    """
    Returns a list of possible actions from the current state.
    Actions are represented as coordinate changes: (dr, dc)
    """
    i, j = state
    ans = list()
    if i + 1 < rows:
        ans.append((1, 0))
    if i != 0:
        ans.append((-1, 0))
    if j + 1 < cols:
        ans.append((0, 1))
    if j != 0:
        ans.append((0, -1))
    return ans

def transition(state, action):
    """
    Given a state and an action, returns the resulting state.
    """
    return ((state[0] + action[0], state[1] + action[1]))

# -----------------------------
# Search Algorithms (Students implement)
# -----------------------------
def bfs(grid, start, goal, rows, cols):
    """
    Breadth-First Search.
    Returns: path (list of states) and nodes explored.
    """
    q = deque()
    q.append((start, 0))
    visited = [[False] * cols for _ in range(rows)]
    count = 0
    results = [[start]]
    visited[start[0]][start[1]] = True
    while q:
        (i, j), pathIndex = q.popleft()
        state = get_state(i, j)
        possible_actions = actions(state, grid, rows, cols)

        for possible_action in possible_actions:
            temp = transition(state, possible_action)
            if visited[temp[0]][temp[1]]:
                continue
            visited[temp[0]][temp[1]] = True
            if grid[temp[0]][temp[1]] == '#':
                continue
            path = results[pathIndex] + [temp]
            results.append(path)

            if goal_test(temp, grid):
                return path, count + 1
            q.append((temp, len(results) - 1))
        count+=1

def dfs(grid, start, goal, rows, cols):
    """
    Depth-First Search.
    Returns: path (list of states) and nodes explored.
    """
    st = []
    st.append((start, [start]))
    visited = [[False] * cols for _ in range(rows)]
    count = 0
    while st:
        (i, j), path = st.pop()
        if visited[i][j]:
            continue
        visited[i][j] = True
        count += 1
        state = get_state(i, j)
        if goal_test(state, grid):
            return path, count
        possible_actions = actions(state, grid, rows, cols)
        for possible_action in possible_actions[::-1]:
            temp = transition(state, possible_action)
            if visited[temp[0]][temp[1]]:
                continue
            if grid[temp[0]][temp[1]] == '#':
                continue
            st.append((temp, path + [temp]))

